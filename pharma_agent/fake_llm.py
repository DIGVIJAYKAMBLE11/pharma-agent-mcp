"""An offline, deterministic stand-in for a chat model.

It lets the tests, CI and the notebooks run end to end with no API key and no cost:

    * bound to tools  -> first turn: call every bound tool once (arguments guessed from the
                         question); second turn: summarise what the tools returned
    * structured RoutePlan   -> an empty plan, so the supervisor falls back to "all agents"
    * structured FinalAnswer -> one key point per evidence id found in the prompt

It is not smart; it only exercises the real plumbing (graph, tools, MCP, guardrail, store).
"""

import re
from typing import Any

from langchain_core.language_models.chat_models import BaseChatModel
from langchain_core.messages import AIMessage, BaseMessage, HumanMessage, ToolMessage
from langchain_core.outputs import ChatGeneration, ChatResult
from langchain_core.runnables import RunnableLambda
from langchain_core.utils.function_calling import convert_to_openai_tool
from pydantic import Field

from .schemas import FinalAnswer, KeyPoint, RoutePlan
from .tools import content_to_text

STOPWORDS = {
    "what", "which", "does", "with", "from", "that", "this", "there", "about", "according",
    "label", "trials", "clinical", "studies", "study", "research", "evidence", "recent", "most",
    "reported", "adverse", "events", "drug", "drugs", "interact", "interactions", "warnings",
    "safety", "should", "their", "these", "known", "summarise", "summarize",
}
EVIDENCE_ID = re.compile(r"\[([a-z][a-z\-]*:[^\]\s]+)\]")


def keyword(question: str) -> str:
    """The longest non-stopword in the question; good enough to fill a 'drug' or 'query' arg."""
    words = [w for w in re.findall(r"[A-Za-z][A-Za-z\-]{3,}", question) if w.lower() not in STOPWORDS]
    return max(words, key=len).lower() if words else "aspirin"


class ScriptedChatModel(BaseChatModel):
    tool_specs: list[dict] = Field(default_factory=list)

    @property
    def _llm_type(self) -> str:
        return "scripted-fake"

    def bind_tools(self, tools, **kwargs) -> "ScriptedChatModel":
        return self.model_copy(update={"tool_specs": [convert_to_openai_tool(t)["function"] for t in tools]})

    def with_structured_output(self, schema, **kwargs):
        return RunnableLambda(lambda messages: self._structured(schema, messages))

    # ---- chat turns ---------------------------------------------------------------------
    def _generate(self, messages: list[BaseMessage], stop=None, run_manager=None, **kwargs) -> ChatResult:
        if self.tool_specs and not any(isinstance(m, ToolMessage) for m in messages):
            question = next((content_to_text(m.content) for m in reversed(messages) if isinstance(m, HumanMessage)), "")
            calls = [
                {"name": spec["name"], "args": self._guess_args(spec, question), "id": f"call_{i}", "type": "tool_call"}
                for i, spec in enumerate(self.tool_specs)
            ]
            message = AIMessage(content="", tool_calls=calls)
        else:
            tool_text = " ".join(content_to_text(m.content) for m in messages if isinstance(m, ToolMessage))
            ids = re.findall(r'"id": "([^"]+)"', tool_text)
            cited = " ".join(f"[{i}]" for i in ids[:8])
            message = AIMessage(content=f"[offline fake model] The tools returned {len(ids)} items: {cited}")
        return ChatResult(generations=[ChatGeneration(message=message)])

    @staticmethod
    def _guess_args(spec: dict, question: str) -> dict[str, Any]:
        word = keyword(question)
        props = spec.get("parameters", {}).get("properties", {})
        required = set(spec.get("parameters", {}).get("required", []))
        args = {}
        for name, prop in props.items():
            is_text = prop.get("type") == "string" and "enum" not in prop
            if is_text and (name in required or name in {"drug", "query", "intervention"}):
                args[name] = word
        return args

    # ---- structured output --------------------------------------------------------------
    @staticmethod
    def _structured(schema, messages):
        if isinstance(messages, list):
            text = " ".join(content_to_text(getattr(m, "content", m)) for m in messages)
        else:
            text = content_to_text(getattr(messages, "content", str(messages)))
        if schema is RoutePlan:
            return RoutePlan(reasoning="offline fake model: no routing, use every agent", tasks=[])
        if schema is FinalAnswer:
            ids = list(dict.fromkeys(EVIDENCE_ID.findall(text)))[:5]
            return FinalAnswer(
                answer=f"[offline fake model] {len(ids)} evidence items were retrieved; see key points.",
                key_points=[KeyPoint(text=f"Evidence retrieved: {i}", citations=[i]) for i in ids],
                confidence="low",
                caveats=["Generated by the offline fake model, not a real LLM."],
            )
        raise NotImplementedError(f"ScriptedChatModel has no script for {schema!r}")
